import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdtemp, mkdir, readdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

// LOCAL ONLY: creates both clusters itself, connects through their private Unix
// sockets, and deletes only its own temporary directory after stopping them.
// No connection URL, password, existing database, or hosted project is accepted.
const here = dirname(fileURLToPath(import.meta.url));
const migrationRoot = resolve(here, '../migrations');
const binaries = process.env.NOOKS_TEST_PG_BIN || '/usr/local/bin';
const args = process.argv.slice(2);
if (args.length && (args.length !== 2 || args[0] !== '--report')) throw new Error('Usage: node supabase/tests/run-restore-drill.mjs [--report file.json]');
const reportPath = args.length ? resolve(args[1]) : null;
const temporary = await mkdtemp(join(tmpdir(), 'nooks-restore-'));
// Environment may contain production connection settings. Pass only the few
// process settings these local binaries need, never inherited PG*, DATABASE_URL,
// or keys. Disable the implicit ~/.pgpass read as well as password prompting.
const emptyPasswordFile = join(temporary, 'empty.pgpass');
const env = { PATH: '/usr/local/bin:/usr/bin:/bin', LC_ALL: 'C', LANG: 'C', PGPASSFILE: emptyPasswordFile, PGSERVICEFILE: emptyPasswordFile };
const database = 'nooks_drill';
const schemas = ['auth', 'public', 'nooks_private', 'nooks_test', 'storage', 'realtime'];
const roles = ['anon', 'authenticated', 'service_role', 'nooks_source_admin'];
const clusters = [];
const timings = {};
const startedAt = new Date().toISOString();
const startedMs = performance.now();
const hash = value => createHash('sha256').update(value).digest('hex');
const quote = value => `'${value.replaceAll("'", "''")}'`;
const identifier = value => `"${value.replaceAll('"', '""')}"`;
function run(name, commandArgs, input) {
  const result = spawnSync(join(binaries, name), commandArgs, { input, env, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024, timeout: 120_000 });
  if (result.status !== 0) throw new Error(`${name} failed: ${result.stderr || result.stdout || result.error}`);
  // Successful dump/restore warnings need review rather than silently passing.
  if ((name === 'pg_dump' || name === 'pg_dumpall' || name === 'pg_restore') && result.stderr.trim()) throw new Error(`${name} reported: ${result.stderr}`);
  return result.stdout;
}
function connection(cluster, db = database) { return ['-h', cluster.socket, '-p', '5432', '-U', cluster.admin, '-w', '-d', db]; }
function sql(cluster, statement, db = database) { return run('psql', ['-X', '-qAt', '-v', 'ON_ERROR_STOP=1', ...connection(cluster, db)], statement).trim(); }
function file(cluster, path) { return run('psql', ['-X', '-qAt', '-v', 'ON_ERROR_STOP=1', ...connection(cluster), '-f', path]); }
async function measure(label, action) {
  const start = performance.now();
  const result = await action();
  timings[label] = Math.round((performance.now() - start) * 1000) / 1000;
  return result;
}
async function startCluster(name, admin) {
  const socket = join(temporary, name);
  await mkdir(socket, { mode: 0o700 });
  const cluster = { socket, admin, data: join(socket, 'data'), startAttempted: false };
  clusters.push(cluster);
  run('initdb', ['-D', cluster.data, '-U', admin, '--auth=trust', '--no-locale', '-E', 'UTF8']);
  // The path is generated by mkdtemp; quote it for postgres' option parser.
  cluster.startAttempted = true;
  run('pg_ctl', ['-D', cluster.data, '-l', join(socket, 'postgres.log'), '-o', `-k '${socket.replaceAll("'", "'\\''")}' -h '' -p 5432 -c unix_socket_permissions=0700`, '-w', 'start']);
  assert.equal(sql(cluster, 'show listen_addresses;', 'postgres'), '', 'TCP must be disabled');
  return cluster;
}
function schemaSnapshot(cluster) {
  // Patched pg_dump releases use a fresh psql restrict token on each invocation.
  // Remove only these client guard lines; retain definitions, owner and ACL SQL.
  let snapshot = run('pg_dump', [...connection(cluster), '--schema-only']).split('\n')
    .filter(line => !/^\\(?:un)?restrict\s/.test(line)).join('\n');
  // PostgreSQL reparses CHECK clauses during restore and can flatten nested AND
  // parentheses. Its own pretty deparser removes only unnecessary parentheses;
  // use that canonical form instead of rewriting SQL expressions ourselves.
  const checks = JSON.parse(sql(cluster, `select coalesce(jsonb_agg(jsonb_build_array(pg_get_constraintdef(c.oid,false),pg_get_constraintdef(c.oid,true)) order by c.oid),'[]'::jsonb) from pg_constraint c join pg_namespace n on n.oid=c.connamespace where c.contype='c' and n.nspname in (${schemas.map(quote).join(',')});`));
  for (const [original, canonical] of checks) snapshot = snapshot.replaceAll(original, canonical);
  return snapshot;
}
function dataSnapshot(cluster) {
  const tableNames = JSON.parse(sql(cluster, `select coalesce(jsonb_agg(jsonb_build_array(n.nspname,c.relname) order by n.nspname,c.relname),'[]'::jsonb) from pg_class c join pg_namespace n on n.oid=c.relnamespace where c.relkind='r' and n.nspname in (${schemas.map(quote).join(',')});`));
  const rows = {};
  for (const [schema, table] of tableNames) rows[`${schema}.${table}`] = JSON.parse(sql(cluster, `select coalesce(jsonb_agg(row_data order by row_data::text),'[]'::jsonb) from (select to_jsonb(t) as row_data from ${identifier(schema)}.${identifier(table)} t) rows;`));
  return rows;
}
function roleSnapshot(cluster) {
  return JSON.parse(sql(cluster, `select jsonb_agg(jsonb_build_object('name',rolname,'superuser',rolsuper,'inherit',rolinherit,'createRole',rolcreaterole,'createDb',rolcreatedb,'login',rolcanlogin,'replication',rolreplication,'bypassRls',rolbypassrls,'connectionLimit',rolconnlimit,'config',rolconfig) order by rolname) from pg_roles where rolname in (${roles.map(quote).join(',')});`));
}
let report;
let failure;
try {
  await writeFile(emptyPasswordFile, '', { mode: 0o600 });
  const version = run('pg_dump', ['--version']).trim();
  const source = await measure('sourceClusterStartMs', () => startCluster('source', 'nooks_source_admin'));
  sql(source, `create database ${database} with template template0;`, 'postgres');
  const migrations = (await readdir(migrationRoot)).filter(name => name.endsWith('.sql')).sort();
  assert.ok(migrations.length, 'migrations must exist');
  const migrationManifest = await Promise.all(migrations.map(async name => ({ name, sha256: hash(await readFile(join(migrationRoot, name))) })));
  await measure('applyMigrationsMs', () => {
    file(source, join(here, 'bootstrap.sql'));
    for (const migration of migrations) file(source, join(migrationRoot, migration));
    sql(source, `create table nooks_test.applied_migrations(name text primary key,sha256 text not null); insert into nooks_test.applied_migrations values ${migrationManifest.map(migration => `(${quote(migration.name)},${quote(migration.sha256)})`).join(',')};`);
  });
  await measure('seedSyntheticDataMs', () => file(source, join(here, 'restore-fixture.sql')));
  const sourceSchema = schemaSnapshot(source);
  const sourceData = dataSnapshot(source);
  const sourceRoles = roleSnapshot(source);
  assert.equal(sourceData['public.nooks_accounts'].length, 2);
  assert.equal(sourceData['public.nooks_artifacts'].length, 8);
  const archive = join(temporary, 'synthetic.dump');
  const globals = join(temporary, 'synthetic-roles.sql');
  await measure('dumpMs', () => {
    run('pg_dumpall', ['-h', source.socket, '-p', '5432', '-U', source.admin, '-w', '-l', database, '--globals-only', '--no-role-passwords', '--file', globals]);
    run('pg_dump', [...connection(source), '--format=custom', '--file', archive]);
  });
  const archiveBytes = (await stat(archive)).size;
  const archiveSha256 = hash(await readFile(archive));
  const restored = await measure('restoreClusterStartMs', () => startCluster('restored', 'nooks_restore_admin'));
  await measure('restoreMs', () => {
    run('psql', ['-X', '-qAt', '-v', 'ON_ERROR_STOP=1', ...connection(restored, 'postgres'), '-f', globals]);
    run('pg_restore', [...connection(restored, 'postgres'), '--create', '--exit-on-error', archive]);
  });
  const restoredSchema = schemaSnapshot(restored);
  if (restoredSchema !== sourceSchema) {
    const sourceLines = sourceSchema.split('\n'); const restoredLines = restoredSchema.split('\n');
    const firstDifference = sourceLines.findIndex((line, index) => line !== restoredLines[index]);
    throw new Error(`Restored schema differs at line ${firstDifference + 1}. Source: ${sourceLines.slice(firstDifference, firstDifference + 6).join('\n')} Restored: ${restoredLines.slice(firstDifference, firstDifference + 6).join('\n')}`);
  }
  const restoredData = dataSnapshot(restored);
  assert.deepEqual(restoredData, sourceData, 'all application, stub platform, fixture and migration-manifest table rows must match');
  assert.deepEqual(roleSnapshot(restored), sourceRoles, 'role attributes and bypass-RLS boundary must survive restore');
  assert.equal(sql(restored, "select pg_get_userbyid(datdba) from pg_database where datname=current_database();"), 'nooks_source_admin', 'database owner must survive restore');
  assert.deepEqual(JSON.parse(sql(restored, 'select jsonb_agg(to_jsonb(m) order by name) from nooks_test.applied_migrations m;')), migrationManifest, 'applied migration filenames and hashes must survive restore');
  const verification = await measure('restoredBehaviorChecksMs', () => file(restored, join(here, 'restore-verify.sql')));
  assert.match(verification, /CAS tests passed/);
  assert.deepEqual(dataSnapshot(restored), sourceData, 'behavior checks must roll back without changing restored fixture data');
  const hardening = await measure('restoredHardeningChecksMs', () => file(restored, join(here, 'production-hardening.sql')));
  assert.match(hardening, /Production hardening tests passed/);
  assert.deepEqual(dataSnapshot(restored), sourceData, 'hardening tests must roll back cleanly');
  report = {
    result: 'passed', startedAt, postgres: version,
    isolation: { clusters: 2, transport: 'private Unix sockets', tcpEnabled: false, existingDatabasesContacted: false, hostedServicesContacted: false, credentialsUsed: false },
    migrations: migrationManifest,
    fixture: { owners: 2, privateArtifacts: 8, artifactFormats: ['note', 'flashcards', 'quiz', 'exam'], tablesCompared: Object.keys(sourceData).length, storageObjects: 0 },
    archive: { format: 'custom', bytes: archiveBytes, sha256: archiveSha256, roleDefinitions: 'pg_dumpall --globals-only --no-role-passwords' },
    fingerprints: { schemaIncludingOwnersAndAcls: hash(sourceSchema), allTableData: hash(JSON.stringify(sourceData)), roleAttributes: hash(JSON.stringify(sourceRoles)) },
    verified: ['all current migrations applied', 'schema, function, constraint, RLS policy, owner and ACL SQL equality (CHECK clauses use PostgreSQL canonical formatting)', 'exact table data and migration hash manifest equality', 'role attributes and database ownership', 'two-owner identity links and private artifact isolation', 'authenticated and anonymous permission denials', 'complete workspace reconstruction', 'owner-prefixed artwork references', 'stale CAS rejection and current-revision save', 'restored hardening regression suite', 'verification transactions rolled back'],
    limitations: ['Synthetic local PostgreSQL with Auth/Storage/Realtime schema stubs; not a hosted Supabase restore.', 'No Storage object metadata or image bytes were copied. Restored artwork references do not establish image availability.', 'No hosted Auth sessions, Realtime delivery, managed roles/extensions/settings, PITR, backup schedules, encryption/retention, alert routing or operator handoff were tested.', 'Timings cover a tiny synthetic fixture and are not production RTO/RPO evidence.'],
    timingsMs: timings,
  };
} catch (error) {
  failure = error;
} finally {
  let stopped = true;
  for (const cluster of [...clusters].reverse()) {
    if (!cluster.startAttempted) continue;
    try { run('pg_ctl', ['-D', cluster.data, '-w', 'stop', '-m', 'fast']); }
    catch (error) { stopped = false; failure ||= error; }
  }
  if (stopped && temporary.startsWith(join(tmpdir(), 'nooks-restore-'))) await rm(temporary, { recursive: true, force: true });
  else if (!stopped) console.error(`Local cluster cleanup needs attention: ${temporary}`);
  if (report) report.cleanup = { clustersStopped: stopped, temporaryFilesRemoved: stopped };
}
if (failure) throw failure;
report.timingsMs.totalIncludingCleanupMs = Math.round((performance.now() - startedMs) * 1000) / 1000;
if (reportPath) await writeFile(reportPath, `${JSON.stringify(report, null, 2)}\n`, { mode: 0o600 });
console.log(JSON.stringify(report, null, 2));
